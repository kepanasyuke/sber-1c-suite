MODEL = classify.train(ROUTING)


def tickets():
    return db.fetch_all("select id, subject, body, created_at, group_name, priority, status, sla_hours, closed_at from tickets order by created_at desc")


def _kb():
    return db.fetch_all("select id, title, body, group_name from kb_articles order by id")


def _ranked(query_tokens, articles):
    docs = [text.tokenize(f"{item['title']} {item['body']}") for item in articles]
    return [{"title": articles[index]["title"], "body": articles[index]["body"], "score": score} for score, index in bm25.rank(query_tokens, docs)[:2] if score > 0]


def _rank(query):
    return _ranked(text.tokenize(query), _kb())


def priority_level(content):
    lowered = content.lower()
    return "критический" if any(word in lowered for word in CRITICAL_WORDS) else "высокий" if any(word in lowered for word in HIGH_WORDS) else "низкий" if any(word in lowered for word in LOW_WORDS) else "средний"


def hours_open(row):
    return round((datetime.now(MSK) - row["created_at"]).total_seconds() / 3600, 1)


def sla_state(row):
    return "закрыт" if row["status"] != "open" else ("просрочено" if hours_open(row) > row["sla_hours"] else "в работе")


def _decorate(row):
    return {**row, "hours_open": hours_open(row), "state": sla_state(row)}


def _draft(subject, articles):
    article = articles[0] if articles else None
    return f"Здравствуйте!\n\nПо обращению «{subject}» предлагаем решение:\n{article['body']}\n\nЕсли шаги не помогли, ответьте в этой заявке — подключим дежурного инженера." if article else f"Здравствуйте!\n\nПо обращению «{subject}» подходящей статьи в базе знаний нет. Заявка направлена дежурному инженеру."


def _summary(verdict, priority, articles):
    return narrative.sentence([
        f"Группа: {verdict['label']}, уверенность модели {verdict['confidence']:.2f}",
        f"приоритет {priority}, срок по SLA {SLA[priority]} ч",
        f"статья базы знаний: {articles[0]['title']}" if articles else "подходящей статьи не найдено",
        f"запасной вариант — {verdict['ranking'][1][1]}" if len(verdict["ranking"]) > 1 else "",
    ])


def _compose(verdict, priority, articles, subject):
    return {**verdict, "priority": priority, "sla": SLA[priority], "articles": articles, "draft": _draft(subject, articles), "summary": _summary(verdict, priority, articles)}


def _route(subject, body):
    content = f"{subject} {body}".strip()
    return _compose(classify.predict(MODEL, content), priority_level(content), _rank(content), subject)


def route(subject, body):
    return _route(subject, body)


def _correct(index):
    model = classify.train([item for position, item in enumerate(ROUTING) if position != index])
    return classify.predict(model, ROUTING[index][1])["label"] == ROUTING[index][0]


def cross_validate():
    hits = sum(1 for index in range(len(ROUTING)) if _correct(index))
    return {"accuracy": round(100 * hits / len(ROUTING), 1), "samples": len(ROUTING)}


def _kpis(rows):
    return {
        "total": len(rows),
        "open": sum(1 for row in rows if row["status"] == "open"),
        "overdue": sum(1 for row in rows if row["state"] == "просрочено"),
        "critical": sum(1 for row in rows if row["priority"] == "критический"),
        "mttr": round(sum(row["hours_open"] for row in rows if row["status"] == "closed") / max(1, sum(1 for row in rows if row["status"] == "closed")), 1),
    }


def overview():
    rows = [_decorate(row) for row in tickets()]
    return {"tickets": rows, "kpis": _kpis(rows), "accuracy": cross_validate(), "articles": len(_kb()), "groups": sorted({item["group_name"] for item in rows})}
